"""
Keeps an agent's change log truthful when the archive is a tree.

An agent's `agent_change_log.md` is copied from its parent, so its entries
describe exactly the changes that are present in its code. What was tried on
other branches is appended by the runner as a clearly marked, generated
section, which is replaced (never accumulated) each time an agent is created.
"""

import re

from pathlib import Path

from base_agent.src.utils.archive_analysis import ArchiveAnalyzer, paired_delta
from base_agent.src.utils.lineage import STATUS_PENDING

BLOCK_START = "<!-- other-branches:start (generated by the runner, do not edit) -->"
BLOCK_END = "<!-- other-branches:end -->"
_BLOCK_RE = re.compile(
    r"\n*<!-- other-branches:start.*?<!-- other-branches:end -->\n*", re.DOTALL
)
MAX_DESCRIPTION_CHARS = 600


def render_other_branches(analyzer: ArchiveAnalyzer, parent_id: int) -> str | None:
    """Describe the agents that are not on the line of descent of a new child
    of `parent_id`, or None if there are none.

    Only agents with a recorded parent are listed: for agents from before
    lineage tracking it is unknown whether they are ancestors, and their
    history is already in the change log they all shared.
    """
    lineage = analyzer.get_lineage()
    own_line = {parent_id, *analyzer.get_ancestors(parent_id)}
    others = [
        record
        for agent_id, record in lineage.items()
        if agent_id not in own_line
        and record.get("parent_id") is not None
        and record.get("status") != STATUS_PENDING
    ]
    if not others:
        return None

    scores_df, _ = analyzer.get_problem_scores_by_iteration()
    lines = [
        "## Attempts on other branches",
        "",
        f"This agent was built from agent {parent_id}. The entries above are the "
        "history of that line of agents only. The agents below are NOT ancestors "
        "of this agent, so their changes are NOT in this codebase. They are listed "
        "so that ideas already tried elsewhere are built on or avoided knowingly. "
        "Scores are relative to each agent's own parent; * marks a difference "
        "that is distinguishable from noise.",
    ]
    for record in others:
        agent_id, agent_parent = record["id"], record["parent_id"]
        if record.get("status") == "failed":
            outcome = "failed to build"
        else:
            delta = paired_delta(scores_df, agent_id, agent_parent)
            outcome = f"vs parent: {delta}" if delta else "not evaluated yet"
        lines += ["", f"### Agent {agent_id} (built from agent {agent_parent}): {outcome}"]
        description = _description(analyzer, agent_id)
        if description:
            lines += ["", description]
    return "\n".join(lines)


def _description(analyzer: ArchiveAnalyzer, agent_id: int) -> str:
    path = analyzer.archive_root / f"agent_{agent_id}" / "agent_code" / "description.txt"
    try:
        text = path.read_text().strip()
    except OSError:
        return ""
    if len(text) > MAX_DESCRIPTION_CHARS:
        text = text[:MAX_DESCRIPTION_CHARS].rstrip() + " [...]"
    return text


def update_change_log(path: Path, other_branches: str | None) -> None:
    """Replace the generated section of a change log with `other_branches`
    (or remove it, if None). The rest of the file is left as it is."""
    text = path.read_text() if path.exists() else ""
    if not text and other_branches is None:
        return
    # Join what was before and after the old section, so that entries the
    # agents appended below it stay part of the log
    text = _BLOCK_RE.sub("\n\n", text).rstrip("\n")
    if other_branches is not None:
        text = f"{text}\n\n{BLOCK_START}\n{other_branches}\n{BLOCK_END}".lstrip("\n")
    path.write_text(text + "\n")
